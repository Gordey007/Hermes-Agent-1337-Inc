"""MinIO client: upload artifacts/reports + presigned link with TTL.

A single source for working with object storage for the evaluator (reports), orchestrator_global
(product artifacts), and sales (presigned delivery after payment).

Buckets (created idempotently on first access):
  hermes-artifacts  — built products, key hermes-artifacts/hab_<tweetid>/v<outer>/<file>
  hermes-reports    — sprint reports, key hermes-reports/hab_<tweetid>/s<sprint>.md

The keys are generated by infra/naming.py (artifact_key / report_key).
"""


from __future__ import annotations

import os
import sys
from datetime import timedelta
from pathlib import Path
from minio import Minio

ENDPOINT = os.getenv("MINIO_ENDPOINT", "localhost:9000")
ACCESS_KEY = os.getenv("MINIO_ACCESS_KEY", "")
SECRET_KEY = os.getenv("MINIO_SECRET_KEY", "")
SECURE = os.getenv("MINIO_SECURE", "")
ARTIFACTS_BUCKET = "hermes-artifacts"
REPORTS_BUCKET = "hermes-reports"
PRESIGN_TTL_HOURS = int(os.getenv("MINIO_PRESIGN_TTL_HOURS", "1"))


def get_client() -> "Minio":
    if Minio is None:
        sys.exit("minio not installed: uv pip install minio")
    return Minio(ENDPOINT, access_key=ACCESS_KEY, secret_key=SECRET_KEY, secure=SECURE)


def ensure_bucket(client: "Minio", bucket: str) -> None:
    if not client.bucket_exists(bucket):
        client.make_bucket(bucket)


def upload_file(local_path: str, bucket: str, key: str) -> str:
    """Upload one file, return object key."""
    client = get_client()
    ensure_bucket(client, bucket)
    client.fput_object(bucket, key, local_path)
    return f"{bucket}/{key}"


def upload_dir(local_dir: str, bucket: str, key_prefix: str) -> list[str]:
    """Recursively upload a directory (for product/ or reports/). Return list of keys."""
    client = get_client()
    ensure_bucket(client, bucket)
    base = Path(local_dir)
    keys: list[str] = []
    for f in base.rglob("*"):
        if f.is_file():
            key = f"{key_prefix.rstrip('/')}/{f.relative_to(base).as_posix()}"
            client.fput_object(bucket, key, str(f))
            keys.append(f"{bucket}/{key}")
    return keys


def presigned_url(bucket: str, key: str, ttl_hours: int | None = None) -> str:
    """Generate a temporary download link (delivery after payment)."""
    client = get_client()
    ttl = timedelta(hours=ttl_hours or PRESIGN_TTL_HOURS)
    return client.presigned_get_object(bucket, key, expires=ttl)


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="MinIO upload/presign")
    sub = ap.add_subparsers(dest="cmd", required=True)
    u = sub.add_parser("upload"); u.add_argument("--local", required=True)
    u.add_argument("--bucket", required=True); u.add_argument("--key", required=True)
    u.add_argument("--dir", action="store_true")
    p = sub.add_parser("presign"); p.add_argument("--bucket", required=True)
    p.add_argument("--key", required=True); p.add_argument("--ttl", type=int)
    args = ap.parse_args()
    if args.cmd == "upload":
        out = (upload_dir(args.local, args.bucket, args.key) if args.dir
               else upload_file(args.local, args.bucket, args.key))
        print(out)
    elif args.cmd == "presign":
        print(presigned_url(args.bucket, args.key, args.ttl))
